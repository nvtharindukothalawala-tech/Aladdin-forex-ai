"""
risk_gate_result.py

Stores detailed Risk Gate results.

Author: Tharindu Kothalwala
Project: Aladdin
"""

from dataclasses import dataclass, field


@dataclass
class RiskGateResult:
    """
    Detailed result generated by the
    Aladdin Risk Gate.
    """

    approved: bool

    risk_amount: float

    risk_reward: float

    reason: str

    gates_passed: list[str] = field(
        default_factory=list
    )

    gates_failed: list[str] = field(
        default_factory=list
    )