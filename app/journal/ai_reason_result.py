from dataclasses import dataclass


@dataclass
class AIReasonResult:
    """
    Explanation generated by AI reasoning layer.
    """

    decision: str

    confidence: float

    technical_reason: str

    news_reason: str

    structure_reason: str

    risk_reason: str

    final_reason: str

    timeframe_reason: str = (
        "Multi-timeframe analysis not available."
    )

    session_reason: str = (
        "Market session analysis not available."
    )

    gate_reason: str = (
        "Decision Gate information not available."
    )

    gates_passed: list[str] | None = None

    gates_failed: list[str] | None = None