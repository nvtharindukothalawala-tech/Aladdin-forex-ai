from dataclasses import dataclass, field


@dataclass
class DecisionGateResult:
    """
    Detailed result generated by the
    Aladdin Decision Gate.

    Confidence fields:

    market_confidence:
        Confidence from the combined
        market intelligence.

    timeframe_confidence:
        Confidence from multi-timeframe
        alignment.

    decision_confidence:
        Final confidence used by the
        Decision Gate.
    """

    action: str

    approved: bool

    reason: str

    market_confidence: float

    timeframe_confidence: float

    decision_confidence: float

    gates_passed: list[str] = field(
        default_factory=list
    )

    gates_failed: list[str] = field(
        default_factory=list
    )

    @property
    def confidence(self):
        """
        Backward-compatible confidence value.

        Existing code that uses:

            result.confidence

        will receive the final decision confidence.
        """

        return self.decision_confidence